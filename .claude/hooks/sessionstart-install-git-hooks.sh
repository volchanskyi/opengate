#!/usr/bin/env bash
# Installs git's native pre-commit and post-commit shims, which fire on every commit, background or
# not; each session rewrites them to exec the hook scripts and prints nothing on success.
set -uo pipefail

root="$(git rev-parse --show-toplevel 2>/dev/null || true)"
[ -n "$root" ] || exit 0

# The hooks dir honors worktrees and core.hooksPath, falling back to .git/hooks.
hooks_dir="$(git rev-parse --git-path hooks 2>/dev/null || echo ".git/hooks")"
case "$hooks_dir" in
  /*) : ;;
  *) hooks_dir="$root/$hooks_dir" ;;
esac
mkdir -p "$hooks_dir" 2>/dev/null || exit 0

for hook in pre-commit post-commit; do
  logic="$root/.claude/hooks/git-$hook.sh"
  [ -f "$logic" ] || continue
  chmod +x "$logic" 2>/dev/null || true
  target="$hooks_dir/$hook"
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# AUTO-GENERATED by .claude/hooks/sessionstart-install-git-hooks.sh — do not edit.' \
    '# The logic lives in the version-controlled script it runs.' \
    "exec \"$logic\" \"\$@\"" >"$target"
  chmod +x "$target"
done
exit 0
