#!/usr/bin/env bash
# Tests for scripts/check-comments: the rules end to end in every language, the
# hook, same-code and stats, then a sweep of this repository.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
TYPESCRIPT="$REPO_ROOT/web/node_modules/typescript"

PASS=0
FAIL=0
FAILURES=()
TMP_DIR="$(mktemp -d)"
CHECKER="$TMP_DIR/check-comments"
trap 'rm -rf "$TMP_DIR"' EXIT

pass() {
  PASS=$((PASS + 1))
  printf '  ok   %s\n' "$1"
}
fail() {
  FAIL=$((FAIL + 1))
  FAILURES+=("$1")
  printf '  FAIL %s\n' "$1" >&2
}

shfmt_pin() {
  (
    # shellcheck source=../lib/tool-versions.sh
    . "$REPO_ROOT/scripts/lib/tool-versions.sh"
    printf '%s' "$TOOL_VERSION_SHFMT"
  )
}

put() {
  mkdir -p "$(dirname "$1")"
  cat >"$1"
}

write_base() {
  mkdir -p "$1/scripts/lib" "$1/scripts/check-comments"
  printf 'export TOOL_VERSION_SHFMT="%s"\n' "$(shfmt_pin)" >"$1/scripts/lib/tool-versions.sh"
  printf 'scripts/check-comments/scope.tsv\tthe scope list\n' >"$1/scripts/check-comments/scope.tsv"
}

