  printf '%s' "$dest"
}

run_checker() {
  local root="$1"
  shift
  OUTPUT=""
  STATUS=0
  OUTPUT="$("$CHECKER" --root "$root" --typescript "$TYPESCRIPT" "$@" 2>&1)" || STATUS=$?
}

expect_status() {
  local name="$1" want="$2"
  if [ "$STATUS" -eq "$want" ]; then
    pass "$name exits $want"
  else
    fail "$name exits $want (got $STATUS: $OUTPUT)"
  fi
}

expect_output() {
  local name="$1" needle="$2"
  if grep -qF -- "$needle" <<<"$OUTPUT"; then
    pass "$name reports $needle"
  else
    fail "$name reports $needle (got: $OUTPUT)"
  fi
}

expect_no_output() {
  local name="$1" needle="$2"
  if grep -qF -- "$needle" <<<"$OUTPUT"; then
    fail "$name does not report $needle (got: $OUTPUT)"
  else
    pass "$name does not report $needle"
  fi
}

