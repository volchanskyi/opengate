  fail "settings register the comment hook"
fi

run_checker "$REPO_ROOT" sweep
if [ "$STATUS" -eq 0 ] && grep -qF " 0 violations" <<<"$OUTPUT"; then
  pass "repository sweep finds no violations ($(tail -1 <<<"$OUTPUT"))"
else
  tail -40 <<<"$OUTPUT" >&2
  fail "repository sweep finds no violations ($(tail -1 <<<"$OUTPUT"))"
fi

echo
echo "Summary: $PASS passed, $FAIL failed"
if [ "$FAIL" -gt 0 ]; then
  printf '  - %s\n' "${FAILURES[@]}" >&2
  exit 1
fi
